#!/usr/bin/env python3
"""pack-modules.py MODROOT KREL ROOTFS MODULES.LIST

Copies the kernel modules a board needs from a `make modules_install` tree into the initramfs tree and writes
/etc/modules, plus the firmware those modules name (modinfo "firmware:") into ROOTFS/lib/firmware.  modules.list: one module per line, `name [params]` is loaded at boot (in this order), `?name` is
shipped but not loaded (insmod/modprobe by hand); '#' starts a comment.  Dependencies come along automatically.
Everything the board does not name stays out of the initramfs (RAM).  Needs the host's depmod (kmod).
"""
import os
import shutil
import subprocess
import sys

modroot, krel, rootfs, listfile, fwdir = sys.argv[1:6]
norm = lambda n: os.path.basename(n).removesuffix(".ko").replace("-", "_")

mdir = os.path.join(modroot, "lib/modules", krel)
subprocess.run(["depmod", "-b", modroot, krel], check=True)
deps, path = {}, {}
for line in open(os.path.join(mdir, "modules.dep")):
    if ":" not in line:
        continue
    mod, rest = line.split(":", 1)
    path[norm(mod)] = mod
    deps[norm(mod)] = [norm(d) for d in rest.split()]

load, ship = [], []                                   # (name, params)
for line in open(listfile):
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    words = line.split()
    (ship if words[0].startswith("?") else load).append((norm(words[0].lstrip("?")), " ".join(words[1:])))
missing = [n for n, _ in load + ship if n not in path]
if missing:
    sys.exit("pack-modules: not built (check the kernel config): " + ", ".join(missing))

def closure(name, seen):
    for d in deps[name]:
        if d not in seen:
            closure(d, seen)
    seen.add(name)
    return seen

need, order = set(), []
for name, _ in load:
    c = closure(name, set())
    # transitive dependency sets are strictly nested, so a smaller set always loads first
    for m in sorted(c, key=lambda m: (len(closure(m, set())), m)):
        if m not in order:
            order.append(m)
    need |= c
for name, _ in ship:
    need |= closure(name, set())

dest = os.path.join(rootfs, "lib/modules", krel)
shutil.rmtree(os.path.join(rootfs, "lib/modules"), ignore_errors=True)
for m in sorted(need):
    d = os.path.join(dest, os.path.dirname(path[m]))
    os.makedirs(d, exist_ok=True)
    shutil.copy2(os.path.join(mdir, path[m]), d)
fw_missing = []
shutil.rmtree(os.path.join(rootfs, "lib/firmware"), ignore_errors=True)
for m in sorted(need):
    names = subprocess.run(["modinfo", "-F", "firmware", os.path.join(mdir, path[m])], check=True,
                           capture_output=True, text=True).stdout.split()
    for name in names:
        src = os.path.join(fwdir, name)
        if not os.path.exists(src):                   # linux-firmware moves files between directories: look by base name
            hits = [os.path.join(r, name.split("/")[-1]) for r, _, fs in os.walk(fwdir) if name.split("/")[-1] in fs]
            src = hits[0] if hits else None
        if src is None:
            fw_missing.append("%s (%s)" % (name, m))
            continue
        os.makedirs(os.path.dirname(os.path.join(rootfs, "lib/firmware", name)), exist_ok=True)
        shutil.copy2(src, os.path.join(rootfs, "lib/firmware", name))
if fw_missing:
    sys.exit("pack-modules: firmware not fetched (add it to scripts/checksums.sha256): " + ", ".join(fw_missing))
for f in ("modules.order", "modules.builtin"):
    shutil.copy2(os.path.join(mdir, f), dest)
subprocess.run(["depmod", "-b", rootfs, krel], check=True)
for f in os.listdir(dest):                            # busybox modprobe reads modules.dep and modules.alias (autoload)
    if f not in ("modules.dep", "modules.alias") and not f.startswith("kernel"):
        os.remove(os.path.join(dest, f))

params = dict(load)
os.makedirs(os.path.join(rootfs, "etc"), exist_ok=True)
with open(os.path.join(rootfs, "etc/modules"), "w") as f:
    f.write("# modules loaded at boot by /etc/init.d/S05modules (generated by scripts/pack-modules.py)\n")
    for m in order:
        f.write((m + " " + params.get(m, "")).rstrip() + "\n")
total = sum(os.path.getsize(os.path.join(r, x)) for r, _, fs in os.walk(dest) for x in fs if x.endswith(".ko"))
fwtotal = sum(os.path.getsize(os.path.join(r, x)) for r, _, fs in os.walk(os.path.join(rootfs, "lib/firmware")) for x in fs)
print("modules: %d shipped (%d KiB), firmware %d KiB, %d loaded at boot: %s" % (len(need), total // 1024, fwtotal // 1024, len(order), " ".join(order)))
