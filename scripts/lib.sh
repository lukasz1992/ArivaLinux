# common functions; sourced by the stage scripts
set -euo pipefail
SDK_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
. "$SDK_ROOT/sdk.conf"

log()  { printf '\033[1;34m[sdk]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[sdk] ERROR:\033[0m %s\n' "$*" >&2; exit 1; }
need() { for c in "$@"; do command -v "$c" >/dev/null || die "missing tool: $c"; done; }

# fetch URL NAME — downloads to $DL_DIR/NAME and checks sha256 from scripts/checksums.sha256
fetch() {
    local url=$1 name=$2 dst="$DL_DIR/$2" want
    mkdir -p "$(dirname "$dst")"
    want=$(awk -v n="$name" '$2==n{print $1}' "$SDK_ROOT/scripts/checksums.sha256")
    [ -n "$want" ] || die "no checksum for $name in scripts/checksums.sha256"
    if [ ! -f "$dst" ] || [ "$(sha256sum "$dst" | cut -d' ' -f1)" != "$want" ]; then
        log "downloading $name"
        curl -sS -L -f --retry 3 -o "$dst.part" "$url" && mv "$dst.part" "$dst"
    fi
    [ "$(sha256sum "$dst" | cut -d' ' -f1)" = "$want" ] || die "bad sha256 checksum: $name"
}

# have_musl_tc - sets TC (directory) and returns 0 if a musl toolchain is available, else returns 1 (no exit)
have_musl_tc() {
    for d in "$MUSL_TC"; do
        if [ -x "$d/bin/${MUSL_PREFIX}gcc" ]; then TC="$d"; return 0; fi
    done
    return 1
}
# musl_tc - the same, but dies when there is none
musl_tc() {
    have_musl_tc || die "no musl toolchain ($MUSL_TC); run scripts/10-toolchain.sh"
}

# make_cc — generates $OUT_DIR/bin/mipsel-sdk-cc: the musl compiler with ALL global flags.
# Compilation (-c/-S/-E): SDK_CFLAGS; linking: SDK_CFLAGS + SDK_LDFLAGS.
make_cc() {
    musl_tc
    mkdir -p "$OUT_DIR/bin"
    local w="$OUT_DIR/bin/mipsel-sdk-cc"
    # vfork() via clone(CLONE_VM|CLONE_VFORK): musl uses SYS_fork for both fork() and vfork(),
    # and the nommu kernel rejects fork() — see toolchain/vfork.S
    "$TC/bin/${MUSL_PREFIX}gcc" $SDK_ARCH -fPIE -c "$SDK_ROOT/toolchain/vfork.S" -o "$OUT_DIR/bin/vfork.o" \
        || die "toolchain/vfork.S: assembly error"
    cat > "$w" <<EOF
#!/bin/sh
# generated by scripts/lib.sh (make_cc) — do not edit
GCC="$TC/bin/${MUSL_PREFIX}gcc"
VFORK="$OUT_DIR/bin/vfork.o"
for a in "\$@"; do
    case "\$a" in
        -c|-S|-E|-M|-MM|-dumpmachine|-dumpversion|-print-*|--version|-v|-###) exec \$GCC $SDK_ARCH -fPIE "\$@";;
        -r) VFORK=;;		# partial link (busybox LTO): vfork.o only in the final program
    esac
done
exec \$GCC $SDK_CFLAGS "\$@" \$VFORK $SDK_LDFLAGS
EOF
    chmod +x "$w"; SDK_CC="$w"
}

# merge_frag KCONFIG_FILE FRAGMENT — applies a fragment (CONFIG_X=y / "# CONFIG_X is not set") onto .config
merge_frag() {
    local cfg=$1 frag=$2 sym
    while IFS= read -r line; do
        sym=$(printf '%s\n' "$line" | sed -n 's/^#\? \?\(CONFIG_[A-Za-z0-9_]*\)[= ].*/\1/p')
        [ -n "$sym" ] || continue
        sed -i "/^$sym=/d;/^# $sym is not set/d" "$cfg"
        printf '%s\n' "$line" >> "$cfg"
    done < "$frag"
}

# check_static_pie FILE... — ELF ET_DYN, no PT_INTERP, LOAD alignment <= SDK_PAGE
check_static_pie() {
    local f
    for f in "$@"; do
        readelf -h "$f" | grep -q 'Type:.*DYN' || die "$f: is not ET_DYN (static-PIE)"
        ! readelf -l "$f" | grep -q INTERP || die "$f: has PT_INTERP (dynamic)"
        readelf -lW "$f" | awk -v max="$SDK_PAGE" '$1=="LOAD"{a=strtonum($NF); if(a>max){print "align " $NF; bad=1}} END{exit bad}' \
            || die "$f: LOAD alignment > $SDK_PAGE (missing -z max-page-size?)"
    done
}
